export const getMenuItemLabel = (section, id, language) => {
  const item = dinnerMenu[section]?.find((option) => option.id === id);
  if (!item) return "";
  const label =
    item[
      language === "pt"
        ? "pt"
        : language === "fr"
          ? "fr"
          : language === "es"
            ? "es"
            : "en"
    ];
  return `${label}${item.diet ? ` (${item.diet})` : ""}`;
};
