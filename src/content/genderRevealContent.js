const legacyPattern =
  /baby\s*shower|punta\s*cana\s*photo\s*edition|pricing\s*&\s*packages|paquetes\s*y\s*precios/i;

export const isCurrentGenderRevealCopy = (value) =>
  Boolean(value) && !legacyPattern.test(String(value));

export const normalizeGenderRevealFaqs = (nodes, language) => {
  const fallback = language === "es" ? spanish.faqs : english.faqs;
  const candidates = (nodes || [])
    .map((node) => ({
      question: node?.title?.trim(),
      answer: node?.content?.content?.trim(),
    }))
    .filter((item) => item.question && item.answer);
  const isCurrentSet =
    candidates.length > 0 &&
    candidates.every(
      ({ question, answer }) =>
        isCurrentGenderRevealCopy(`${question} ${answer}`) &&
        !/\$\s*\d|fixed package|paquete fijo/i.test(`${question} ${answer}`),
    );

  if (!isCurrentSet) return fallback;

  const managedQuestions = new Set(
    candidates.map(({ question }) => question.toLocaleLowerCase()),
  );

  return [
    ...candidates,
    ...fallback.filter(
      ({ question }) => !managedQuestions.has(question.toLocaleLowerCase()),
    ),
  ];
};

export const getGenderRevealContent = (language) =>
  language === "es" ? spanish : english;
