const walkText = (node) => {
  if (!node) return "";
  if (node.nodeType === "text") return node.value || "";
  return (node.content || []).map(walkText).join("");
};

const parseContentfulConfig = (raw) => {
  if (!raw) return null;
  try {
    const document = typeof raw === "string" ? JSON.parse(raw) : raw;
    const text = walkText(document).trim();
    return text.startsWith("{") ? JSON.parse(text) : null;
  } catch {
    return null;
  }
};

const mergeContent = (base, override) => {
  if (!override) return base;
  return Object.keys(override).reduce(
    (result, key) => ({
      ...result,
      [key]:
        override[key] &&
        typeof override[key] === "object" &&
        !Array.isArray(override[key]) &&
        typeof result[key] === "object" &&
        !Array.isArray(result[key])
          ? { ...result[key], ...override[key] }
          : override[key],
    }),
    { ...base },
  );
};

export const getCorporateEventContent = (language, rawConfig) => {
  if (language === "pt") return portugueseCorporateEventContent;
  if (language === "fr") return frenchCorporateEventContent;
  const base = language === "es" ? spanishContent : englishContent;
  return mergeContent(base, parseContentfulConfig(rawConfig));
};

export const corporateEventFallbacks = {
  "en-US": englishContent,
  es: spanishContent,
  pt: portugueseCorporateEventContent,
  fr: frenchCorporateEventContent,
};
