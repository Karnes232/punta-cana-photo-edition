const mergeManagedContent = (base, override) => {
  if (!override || typeof override !== "object" || Array.isArray(override)) {
    return base;
  }

  return Object.entries(override).reduce(
    (result, [key, value]) => {
      result[key] =
        value &&
        typeof value === "object" &&
        !Array.isArray(value) &&
        base?.[key] &&
        typeof base[key] === "object" &&
        !Array.isArray(base[key])
          ? mergeManagedContent(base[key], value)
          : value;
      return result;
    },
    { ...base },
  );
};

const parseManagedContent = (raw) => {
  if (!raw) return null;

  try {
    const document = JSON.parse(raw);
    const readText = (node) => {
      if (typeof node?.value === "string") return node.value;
      return (node?.content || []).map(readText).join(" ");
    };
    const text = readText(document).trim();
    const start = text.indexOf("{");
    const end = text.lastIndexOf("}");
    return start >= 0 && end > start
      ? JSON.parse(text.slice(start, end + 1))
      : null;
  } catch {
    return null;
  }
};

export const getWeddingPlannerContent = (language, managedRaw) =>
  mergeManagedContent(
    language === "es" ? spanish : english,
    parseManagedContent(managedRaw),
  );

export const normalizeWeddingFaqs = (nodes, language) => {
  const fallback = getWeddingPlannerContent(language).faqs;
  const cmsFaqs = (nodes || [])
    .map((item) => ({
      question: item?.title || "",
      answer: item?.content?.content || "",
    }))
    .filter(
      (item) =>
        item.question &&
        item.answer &&
        !/receive photos|recibir.*foto|photo.*video|foto.*video|\$200|canceling.*money back/i.test(
          `${item.question} ${item.answer}`,
        ),
    );

  const seen = new Set();
  return [...cmsFaqs, ...fallback]
    .filter((item) => {
      const key = item.question.toLowerCase();
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .slice(0, 6);
};

export const weddingPlannerFallbacks = { "en-US": english, es: spanish };
